export const LYCEE_DEFAULT_ORDER = LYCEE_PHOTOS.map((photo) => photo.id);

export function isLyceePhotoOrder(value: unknown): value is string[] {
  if (!Array.isArray(value) || value.length !== LYCEE_DEFAULT_ORDER.length) return false;
  const allowed = new Set<string>(LYCEE_DEFAULT_ORDER);
  const seen = new Set<string>();
  for (const id of value) {
    if (typeof id !== "string" || !allowed.has(id) || seen.has(id)) return false;
    seen.add(id);
  }
  return true;
}
